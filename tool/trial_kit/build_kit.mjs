#!/usr/bin/env node
// Build 8 (docs/PLAN.md §4, Must 5 and 6): generates the parts of the trial
// kit that follow from the plan, so they never drift from it.
//
//   node tool/trial_kit/build_kit.mjs
//
// Writes:
//   docs/trial/question_checklist.csv  the 731 questions the trial needs,
//       one row each (level, block, part, number, source paper, import
//       route, checker, state). The owner edits the source, checker and
//       state columns; a rerun keeps what was typed (matched by id).
//   docs/trial/blackbox_template.md    one black-box table per build, the
//       rows taken from the "Acceptance walk" lists in docs/PLAN.md §4.
//   docs/TRIAL_KIT.md (between the BEGIN/END markers) the 731-row table.
import {existsSync, readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const CSV = join(ROOT, "docs", "trial", "question_checklist.csv");
const KIT = join(ROOT, "docs", "TRIAL_KIT.md");
const BLACKBOX = join(ROOT, "docs", "trial", "blackbox_template.md");

// The standard formats (docs/PLAN.md §3): [part, questions].
const FORMATS = {
  1: [["listening", 20], ["reading", 20]],
  2: [["listening", 35], ["reading", 25]],
  3: [["listening", 40], ["reading", 30], ["writing", 10]],
  4: [["listening", 45], ["reading", 40], ["writing", 15]],
  5: [["listening", 45], ["reading", 45], ["writing", 10]],
  6: [["listening", 50], ["reading", 50], ["writing", 1]],
};
const ROUTE = {
  practice: "paper reader or CSV/JSON import",
  listening: "paper reader + one recording per sheet + Answer key dialog",
  reading: "paper reader (Scan paper), proofread",
  writing: "paper reader; typed answers checked by the matcher",
};

export function plannedRows() {
  const rows = [];
  for (let level = 1; level <= 6; level += 1) {
    for (let n = 1; n <= 15; n += 1) {
      rows.push({id: `P${level}-${String(n).padStart(2, "0")}`, level: `HSK ${level}`,
        block: "practice package", part: "mixed", no: n, route: ROUTE.practice});
    }
  }
  const code = (level, tag) => {
    let no = 0;
    for (const [part, count] of FORMATS[level]) {
      for (let i = 1; i <= count; i += 1) {
        no += 1;
        rows.push({id: `${tag}-${String(no).padStart(3, "0")}`, level: `HSK ${level}`,
          block: tag.startsWith("C") ? "test code" : "extra HSK 3 code", part, no,
          route: ROUTE[part]});
      }
    }
  };
  for (let level = 1; level <= 6; level += 1) code(level, `C${level}`);
  code(3, "X3A");
  code(3, "X3B");
  return rows;
}

const csvCell = (v) => {
  const s = String(v ?? "");
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

function readExisting() {
  if (!existsSync(CSV)) return {};
  const lines = readFileSync(CSV, "utf8").replace(/^﻿/, "").split(/\r?\n/).filter(Boolean);
  const out = {};
  for (const line of lines.slice(1)) {
    const cells = line.match(/("([^"]|"")*"|[^,]*)(,|$)/g).map((c) =>
      c.replace(/,$/, "").replace(/^"|"$/g, "").replace(/""/g, '"'));
    out[cells[0]] = {source: cells[6], checker: cells[7], state: cells[8]};
  }
  return out;
}

function writeChecklist(rows) {
  const old = readExisting();
  const header = ["id", "level", "block", "part", "no", "import_route", "source_paper",
    "checker", "state"];
  const body = rows.map((r) => {
    const o = old[r.id] || {};
    return [r.id, r.level, r.block, r.part, r.no, r.route, o.source || "",
      o.checker || "", o.state || "to do"];
  });
  writeFileSync(CSV, [header, ...body].map((r) => r.map(csvCell).join(",")).join("\n") + "\n");
  return body;
}

function writeKitTable(body) {
  const kit = readFileSync(KIT, "utf8");
  const begin = "<!-- BEGIN CHECKLIST (generated by tool/trial_kit/build_kit.mjs) -->";
  const end = "<!-- END CHECKLIST -->";
  const i = kit.indexOf(begin);
  const j = kit.indexOf(end);
  if (i < 0 || j < 0) throw new Error("markers missing in docs/TRIAL_KIT.md");
  const table = ["| id | level | block | part | no | import route | source paper | checker | state |",
    "|---|---|---|---|---|---|---|---|---|",
    ...body.map((r) => `| ${r.map((c) => String(c).replace(/\|/g, "/")).join(" | ")} |`)];
  writeFileSync(KIT, `${kit.slice(0, i + begin.length)}\n${table.join("\n")}\n${kit.slice(j)}`);
}

export function acceptanceWalks(planText) {
  const builds = [];
  const parts = planText.replace(/\r\n/g, "\n").split(/^### (Build [^\n]+)$/m);
  for (let k = 1; k < parts.length; k += 2) {
    const title = parts[k].replace(/ — (done|\*\*NEXT\*\*).*$/, "").trim();
    const body = parts[k + 1];
    const a = body.indexOf("**Acceptance walk");
    if (a < 0) continue;
    const rest = body.slice(a).split("\n").slice(1);
    const steps = [];
    let cur = null;
    for (const line of rest) {
      const m = line.match(/^(\d+)\.\s+(.*)$/);
      if (m) {
        if (cur) steps.push(cur);
        cur = m[2].trim();
      } else if (cur !== null && /^\s{2,}\S/.test(line)) {
        cur += ` ${line.trim()}`;
      } else if (cur !== null && line.trim() === "") {
        // a blank line between steps is allowed; the list ends at a heading
      } else if (cur !== null && /^\*\*|^###/.test(line)) {
        break;
      }
    }
    if (cur) steps.push(cur);
    if (steps.length) builds.push({title, steps});
  }
  return builds;
}

function writeBlackbox(builds) {
  const out = ["# Black-box test tables (template)", "",
    "Generated by `tool/trial_kit/build_kit.mjs` from the acceptance walks in",
    "`docs/PLAN.md` §4. One table per build; fill **Result** (Sesuai / Tidak",
    "sesuai) and **Notes** during the trial. The book's black-box chapter takes",
    "these tables as they are.", ""];
  for (const b of builds) {
    out.push(`## ${b.title}`, "", "| No | Scenario (input and action) | Expected result | Result | Notes |",
      "|---|---|---|---|---|");
    b.steps.forEach((s, i) => {
      const [action, ...expect] = s.replace(/\|/g, "/").split(/:\s+/);
      out.push(`| ${i + 1} | ${action} | ${expect.join(": ") || "as described"} |  |  |`);
    });
    out.push("");
  }
  writeFileSync(BLACKBOX, out.join("\n"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const rows = plannedRows();
  const body = writeChecklist(rows);
  writeKitTable(body);
  const builds = acceptanceWalks(readFileSync(join(ROOT, "docs", "PLAN.md"), "utf8"));
  writeBlackbox(builds);
  console.log(`checklist: ${rows.length} questions; black-box: ${builds.length} builds, ` +
    `${builds.reduce((t, b) => t + b.steps.length, 0)} rows`);
}
